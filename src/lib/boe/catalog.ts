/** 근거 게이트: 인용한 청크가 실제로 있는 문항만 통과시킨다. */
export function gatedItems(bookId: string) {
  const ev = new Set((EVIDENCE[bookId] ?? []).map((e) => e.id));
  if (ev.size < 2) return { ok: false as const, items: [] as QuizItem[] };
  const items = QUIZ.filter((q) => q.book === bookId && q.cites.every((c) => ev.has(c)));
  return { ok: items.length > 0, items };
}

