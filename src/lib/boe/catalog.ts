/** 책·도서관마다 늘 같은 값이 나오는 가짜 재고 */
export function holdingsFor(bookId: string): Record<string, Holding | undefined> {
  const out: Record<string, Holding | undefined> = {};
  for (const l of LIBRARIES) {
    let h = 2166136261;
    for (const ch of bookId + l.code) h = Math.imul(h ^ ch.charCodeAt(0), 16777619) >>> 0;
    if (h % 5 === 0) { out[l.code] = undefined; continue; }
    const total = 1 + (h % 3);
    const out_ = (h >> 3) % (total + 1);
    out[l.code] = { total, out: out_, history: [(h >> 5) % 10, (h >> 9) % 8] };
  }
  return out;
}
