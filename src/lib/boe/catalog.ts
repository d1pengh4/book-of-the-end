export const wordsOf = (b: Book) => b.pages * 170; // 쪽당 약 170어절로 본다

/** 쪽 범위로 나눈 읽기 청크. 실제 목차가 없으니 20쪽 단위로 자른다. */
export function chunksOf(b: Book, wpm: number, pagesPer = 20) {
  const out = [];
  for (let p = 1, i = 0; p <= b.pages; p += pagesPer, i++) {
    const end = Math.min(b.pages, p + pagesPer - 1);
    out.push({ id: `${b.id}-${i}`, label: `${p}~${end}쪽`, minutes: Math.max(5, Math.round(((end - p + 1) * 170) / wpm)), importance: 1 });
  }
  return out;
}

